        [Fact]
        public void FormatTables_starts_each_index_on_a_new_page()
        {
            string path = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N") + ".docx");
            try
            {
                Paragraph P(string style, string text)
                {
                    return new Paragraph(new ParagraphProperties(new ParagraphStyleId { Val = style }), new Run(new Text(text)));
                }

                using (var doc = WordprocessingDocument.Create(path, WordprocessingDocumentType.Document))
                {
                    var main = doc.AddMainDocumentPart();
                    main.Document = new Document(new Body(
                        P("Heading2", "Device Information"),
                        P("Heading2", "Communication Specific Parameters"),
                        P("Heading1", "0x1000 - Device type"),
                        P("Heading1", "0x1001 - Error register"),
                        P("Heading1", "Not an index")));
                    main.Document.Save();
                }

                DocumentationGenWord.FormatTables(path);

                using (var doc = WordprocessingDocument.Open(path, false))
                {
                    var ps = doc.MainDocumentPart.Document.Body.Elements<Paragraph>().ToList();
                    Assert.Null(ps[0].ParagraphProperties.PageBreakBefore);
                    Assert.NotNull(ps[1].ParagraphProperties.PageBreakBefore);   // chapter heading carries the first break
                    Assert.Null(ps[2].ParagraphProperties.PageBreakBefore);
                    Assert.NotNull(ps[3].ParagraphProperties.PageBreakBefore);
                    Assert.Null(ps[4].ParagraphProperties.PageBreakBefore);
                }
            }
            finally
            {
                if (File.Exists(path))
                    File.Delete(path);
            }
        }

