        [Fact]
        public void FormatTables_bands_rows_and_sets_borders()
        {
            string path = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N") + ".docx");
            try
            {
                using (var doc = WordprocessingDocument.Create(path, WordprocessingDocumentType.Document))
                {
                    var main = doc.AddMainDocumentPart();
                    var table = new Table(new TableProperties(), new TableGrid(new GridColumn { Width = "2000" }, new GridColumn { Width = "2000" }));
                    for (int r = 0; r < 4; r++)
                    {
                        table.Append(new TableRow(
                            new TableCell(new Paragraph(new Run(new Text("a" + r)))),
                            new TableCell(new Paragraph(new Run(new Text("b" + r))))));
                    }
                    main.Document = new Document(new Body(table));
                    main.Document.Save();
                }

                DocumentationGenWord.FormatTables(path);

                using (var doc = WordprocessingDocument.Open(path, false))
                {
                    var t = doc.MainDocumentPart.Document.Body.Descendants<Table>().Single();
                    var rows = t.Elements<TableRow>().ToList();

                    Assert.Equal(TableLayoutValues.Autofit, t.GetFirstChild<TableProperties>().TableLayout.Type.Value);
                    Assert.Equal("1440", t.GetFirstChild<TableProperties>().TableIndentation.Width.Value.ToString());

                    // Row 0 is the header (distinct cell text), data rows 1..3; the second data row (index 2) is shaded.
                    Assert.Null(rows[1].Elements<TableCell>().First().TableCellProperties.Shading);
                    Assert.Equal("F2F2F2", rows[2].Elements<TableCell>().First().TableCellProperties.Shading.Fill.Value);
                    Assert.Null(rows[3].Elements<TableCell>().First().TableCellProperties.Shading);

                    Assert.NotNull(rows[0].Elements<TableCell>().First().TableCellProperties.TableCellBorders.TopBorder);
                    Assert.NotNull(rows[3].Elements<TableCell>().First().TableCellProperties.TableCellBorders.BottomBorder);
                }
            }
            finally
            {
                if (File.Exists(path))
                    File.Delete(path);
            }
        }
