        [Fact]
        public void FormatTables_pushes_title_below_first_page_header_logo()
        {
            string path = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N") + ".docx");
            try
            {
                using (var doc = WordprocessingDocument.Create(path, WordprocessingDocumentType.Document))
                {
                    var main = doc.AddMainDocumentPart();

                    // First-page header holding a floating picture whose bottom edge is 4653 twips down the page:
                    // header distance 680 + (1961515 + 561600) EMU / 635.
                    var headerPart = main.AddNewPart<HeaderPart>();
                    var anchor = new DocumentFormat.OpenXml.Drawing.Wordprocessing.Anchor(
                        new DocumentFormat.OpenXml.Drawing.Wordprocessing.VerticalPosition(
                            new DocumentFormat.OpenXml.Drawing.Wordprocessing.PositionOffset("1961515"))
                        { RelativeFrom = DocumentFormat.OpenXml.Drawing.Wordprocessing.VerticalRelativePositionValues.Paragraph },
                        new DocumentFormat.OpenXml.Drawing.Wordprocessing.Extent { Cx = 2480400L, Cy = 561600L });
                    headerPart.Header = new Header(new Paragraph(new Run(new Drawing(anchor))));
                    headerPart.Header.Save();

                    var title = new Paragraph(
                        new ParagraphProperties(new ParagraphStyleId { Val = "Title" }),
                        new Run(new Text("Object Dictionary")));
                    var sect = new SectionProperties(
                        new HeaderReference { Type = HeaderFooterValues.First, Id = main.GetIdOfPart(headerPart) },
                        new PageSize { Width = 11900, Height = 16840 },
                        new PageMargin { Top = 1134, Right = 1554, Bottom = 1440, Left = 1440, Header = 680, Footer = 397, Gutter = 0 },
                        new TitlePage());
                    main.Document = new Document(new Body(title, sect));
                    main.Document.Save();
                }

                DocumentationGenWord.FormatTables(path);

                using (var doc = WordprocessingDocument.Open(path, false))
                {
                    var p = doc.MainDocumentPart.Document.Body.Elements<Paragraph>().First();
                    // 4653 + 284 gap - 1134 top margin
                    Assert.Equal("3803", p.ParagraphProperties.SpacingBetweenLines.Before.Value);
                }
            }
            finally
            {
                if (File.Exists(path))
                    File.Delete(path);
            }
        }

